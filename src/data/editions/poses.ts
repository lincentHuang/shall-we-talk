/**
 * 深夜限定「姿勢圖解」：每張牌的拱窗裡畫一張星座風格的抽象人形圖（只有線條和關節，不畫身體細節），
 * 下方文字說明怎麼做。人形不分性別，用金色與玫瑰色區分兩個人。
 *
 * 座標系是 200×150 的 viewBox；side 是側面圖（地板／床面在 y=128），top 是從上往下看。
 * 每個人：head 頭的圓心、neck 肩頸、hip 骨盆，arms／legs 各兩組 [手肘, 手]、[膝蓋, 腳]，
 * 第一組是靠近觀看者的那一側（畫實線），第二組是遠側（畫淡一點）。
 *
 * 編號（陣列順序）就是題目編號 ad-pose-N，寫好就不要調換順序；新增往後加。
 */

export type Pt = [number, number];

export type Figure = {
  head: Pt;
  neck: Pt;
  hip: Pt;
  arms: [Pt, Pt][];
  legs: [Pt, Pt][];
};

