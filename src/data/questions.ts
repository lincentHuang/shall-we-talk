/**
 * 題目適用對象：
 * - 未標註：任何人都能用，包含「我自己」；題目只問答題的人自己
 * - others：要有別人在場（兩人以上）
 * - duo：只限兩個人
 * - group：三人以上才有的玩法，例如「在場的人裡，誰最⋯」
 * - known：彼此已經認識一段時間（排除新朋友、我自己）
 * - romance：曖昧對象或戀人，而且只有兩個人
 * - couple：只限戀人・伴侶，而且只有兩個人
 */
export type Audience = 'others' | 'duo' | 'group' | 'known' | 'romance' | 'couple';

