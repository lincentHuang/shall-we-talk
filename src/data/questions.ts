/** 依談話對象分開寫的專屬題庫，見 src/data/partners/；新朋友和我自己只用通用題 */
const BY_PARTNER: Partial<Record<PartnerId, Bank>> = {
  friend: FRIEND,
  family: FAMILY,
  colleague: COLLEAGUE,
  crush: CRUSH,
  partner: PARTNER,
};

function expand(bank: Bank, partner?: PartnerId): Question[] {
  return (Object.keys(bank) as CardKind[]).flatMap((kind) =>
    (bank[kind] ?? []).map(([n, level, text, aud]) => ({
      // 通用題的 id 是「主題-編號」，專屬題前面多一段對象，收藏才不會撞號
      id: partner ? `${partner}-${kind}-${n}` : `${kind}-${n}`,
      kind,
      level,
      text,
      aud,
      partner,
    })),
  );
}

export const QUESTIONS: Question[] = [
  ...expand(BANK),
  ...(Object.keys(BY_PARTNER) as PartnerId[]).flatMap((p) => expand(BY_PARTNER[p]!, p)),
  // 特別版的牌種（ad-、pa-）只屬於自己的版本，id 不會和經典版撞號
  ...expand(AFTERDARK).map(withPose),
  ...expand(PARENTS),
];

/** 姿勢圖解牌 ad-pose-N 對應 POSES 的第 N 個 */
function withPose(q: Question): Question {
  return q.kind === 'ad-pose' ? { ...q, pose: POSES[Number(q.id.slice('ad-pose-'.length)) - 1] } : q;
}

export const QUESTION_BY_ID: Record<string, Question> = Object.fromEntries(QUESTIONS.map((q) => [q.id, q]));

/** 題目是否適合這一桌：談話對象＋人數；專屬題只給對應的談話對象 */
export function fitsTable(q: Question, partner: PartnerId, crowd: Crowd): boolean {
  if (q.partner && q.partner !== partner) return false;
  switch (q.aud) {
    case undefined:
      return true;
    case 'others':
      return crowd !== 'self';
    case 'duo':
      return crowd === 'pair';
    case 'group':
      return crowd === 'group';
    case 'known':
      return crowd !== 'self' && partner !== 'stranger';
    case 'romance':
      return crowd === 'pair' && (partner === 'crush' || partner === 'partner');
    case 'couple':
      return crowd === 'pair' && partner === 'partner';
  }
}

/** 把題目裡的 {TA} 換成實際的說法：兩個人是「對方」，三人以上是「左手邊這位」 */
export function phrase(text: string, crowd: Crowd = 'pair') {
  return text.split('{TA}').join(crowd === 'group' ? '左手邊這位' : '對方');
}
