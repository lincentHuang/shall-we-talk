export const QUESTIONS: Question[] = (Object.keys(BANK) as CardKind[]).flatMap((kind) =>
  BANK[kind].map(([n, level, text, aud]) => ({ id: `${kind}-${n}`, kind, level, text, aud })),
);

export const QUESTION_BY_ID: Record<string, Question> = Object.fromEntries(QUESTIONS.map((q) => [q.id, q]));

/** 題目是否適合這一桌：談話對象＋人數 */
export function fitsTable(q: Question, partner: PartnerId, crowd: Crowd): boolean {
  switch (q.aud) {
    case undefined:
      return true;
    case 'others':
      return crowd !== 'self';
    case 'duo':
      return crowd === 'pair';
    case 'group':
      return crowd === 'group';
    case 'known':
      return crowd !== 'self' && partner !== 'stranger';
    case 'romance':
      return crowd === 'pair' && (partner === 'crush' || partner === 'partner');
    case 'couple':
      return crowd === 'pair' && partner === 'partner';
  }
}

/** 把題目裡的 {TA} 換成實際的說法：兩個人是「對方」，三人以上是「左手邊這位」 */
export function phrase(text: string, crowd: Crowd = 'pair') {
  return text.split('{TA}').join(crowd === 'group' ? '左手邊這位' : '對方');
}
